describe("real ingredient lines", () => {
  it("has at least 40 examples", () => {
    expect(ROWS.length).toBeGreaterThanOrEqual(40);
  });

  it.each(ROWS)("%s", (line, quantity, quantityMax, unit, food, note, size) => {
    expect(parseIngredient(line)).toEqual({
      status: "parsed",
      raw: line,
      quantity,
      quantityMax,
      unit,
      size: size ?? null,
      food,
      note,
    });
  });
});

describe("lines that aren't ingredients", () => {
  it.each([
    ["", "empty line"],
    ["For the sauce:", "section heading"],
    ["Topping:", "section heading"],
    ["3 cups", "no food name"],
    ["1 tablespoon", "no food name"],
    ["2 1/2", "no food name"],
    ["***", "no food name"],
  ])("%o is unparsed: %s", (line, reason) => {
    expect(parseIngredient(line)).toEqual({
      status: "unparsed",
      raw: line,
      reason,
    });
  });
});
